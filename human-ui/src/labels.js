export function employeeLabel(e) {
  return `${employees[e.kind] || e.kind} · ${e.id.includes(":ceo") ? "CEO" : e.id}`;
}
export function ability(c) {
  return (
    [
      c.hire && `招聘 ${c.hire}`,
      c.train && `培训 ${c.train} 级`,
      c.slots && `管理 ${c.slots} 人`,
      c.quantity && `产出 ${c.quantity}`,
      c.marketing && "发起营销",
      c.price && `单价 ${c.price > 0 ? "+" : ""}${c.price}`,
    ]
      .filter(Boolean)
      .join(" / ") || "特殊能力"
  );
}
